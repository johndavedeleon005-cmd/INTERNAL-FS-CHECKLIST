export function EmailReportModal({
  report,
  onClose,
  onSentSuccess,
}: EmailReportModalProps) {
  const reportData = useMemo(() => computeReportEmailData(report), [report]);

  const [toInput, setToInput] = useState('');
  const [ccInput, setCcInput] = useState('');
  const [subject, setSubject] = useState(
    `Store Inspection Compliance Report — ${reportData.reportNo}`
  );
  const [senderNote, setSenderNote] = useState('');
  const [includeAiSuggestions, setIncludeAiSuggestions] = useState(true);

  // Email-only AI analysis state (strictly local to this modal — never saved to checklist/PDF/Excel)
  const [aiAnalysis, setAiAnalysis] = useState<EmailAiAnalysis | null>(null);
  const [isGeneratingAi, setIsGeneratingAi] = useState(false);
  const [aiError, setAiError] = useState<string | null>(null);

  // Gmail OAuth in-memory session state
  const [gmailToken, setGmailToken] = useState<string | null>(() =>
    getGmailAccessToken()
  );
  const [gmailEmail, setGmailEmail] = useState<string | null>(() =>
    getGmailAccountEmail()
  );
  const [isConnectingGmail, setIsConnectingGmail] = useState(false);

  // Validation, confirmation & send state
  const [formError, setFormError] = useState<string | null>(null);
  const [confirmingSend, setConfirmingSend] = useState(false);
  const [isSending, setIsSending] = useState(false);
  const [sentResult, setSentResult] = useState<{
    to: string[];
    cc: string[];
    subject: string;
    messageId: string;
  } | null>(null);

  const hasAutoGeneratedRef = useRef(false);

  const handleGenerateAi = useCallback(async () => {
    setIsGeneratingAi(true);
    setAiError(null);
    try {
      const result = await fetchAiDeviationSuggestions(report);
      setAiAnalysis(result);
    } catch (err) {
      setAiError(
        err instanceof Error
          ? err.message
          : 'Could not generate AI deviation suggestions.'
      );
    } finally {
      setIsGeneratingAi(false);
    }
  }, [report]);

  // Automatically generate email-only AI deviation suggestions when the modal opens
  useEffect(() => {
    if (hasAutoGeneratedRef.current) return;
    hasAutoGeneratedRef.current = true;
    void handleGenerateAi();
  }, [handleGenerateAi]);

  // Close on Escape unless sending
  useEffect(() => {
    const onKeyDown = (e: KeyboardEvent) => {
      if (e.key === 'Escape' && !isSending) {
        if (confirmingSend) {
          setConfirmingSend(false);
        } else {
          onClose();
        }
      }
    };
    window.addEventListener('keydown', onKeyDown);
    return () => window.removeEventListener('keydown', onKeyDown);
  }, [confirmingSend, isSending, onClose]);

  const handleConnectGmail = async (forceAccountSelect = false) => {
    setIsConnectingGmail(true);
    setFormError(null);
    try {
      const res = await connectGmailForSending(forceAccountSelect);
      setGmailToken(res.accessToken);
      setGmailEmail(res.email);
    } catch (err) {
      const msg = err instanceof Error ? err.message : String(err);
      if (!msg.includes('popup-closed-by-user')) {
        setFormError(
          'Could not connect Gmail. Please allow popups, approve Gmail send access, and try again.'
        );
      }
    } finally {
      setIsConnectingGmail(false);
    }
  };

  const updateSuggestionField = (
    itemNumber: number,
    field: keyof Omit<DeviationAiSuggestion, 'itemNumber'>,
    value: string
  ) => {
    setAiAnalysis((prev) => {
      if (!prev) return prev;
      return {
        ...prev,
        suggestions: prev.suggestions.map((s) =>
          s.itemNumber === itemNumber ? { ...s, [field]: value } : s
        ),
      };
    });
  };

  const handleRequestConfirmation = () => {
    setFormError(null);

    const parsedTo = parseAndValidateEmailList(toInput);
    if (parsedTo.invalid.length > 0) {
      setFormError(
        `Invalid recipient email address: ${parsedTo.invalid.join(', ')}`
      );
      return;
    }
    if (parsedTo.valid.length === 0) {
      setFormError('Enter at least one valid recipient email in the To field.');
      return;
    }

    const parsedCc = parseAndValidateEmailList(ccInput);
    if (parsedCc.invalid.length > 0) {
      setFormError(`Invalid CC email address: ${parsedCc.invalid.join(', ')}`);
      return;
    }

    if (!stripHeaderBreaks(subject)) {
      setFormError('Please enter an email subject.');
      return;
    }

    if (!gmailToken) {
      setFormError(
        'Connect your Google account with Gmail permission before sending.'
      );
      return;
    }

    if (includeAiSuggestions && isGeneratingAi) {
      setFormError(
        'Please wait for AI suggestions to finish generating, or uncheck AI suggestions to send immediately.'
      );
      return;
    }

    setConfirmingSend(true);
  };

  const handleConfirmSend = async () => {
    const parsedTo = parseAndValidateEmailList(toInput);
    const parsedCc = parseAndValidateEmailList(ccInput);
    const cleanSubject = stripHeaderBreaks(subject);

    if (!gmailToken || parsedTo.valid.length === 0) {
      setConfirmingSend(false);
      return;
    }

    setIsSending(true);
    setFormError(null);

    try {
      const payload = {
        reportData,
        senderNote,
        includeAiSuggestions,
        aiAnalysis: includeAiSuggestions ? aiAnalysis : null,
      };
      const plainText = buildEmailPlainText(payload);
      const html = buildEmailHtml(payload);

      const sent = await sendInspectionEmailViaGmail({
        accessToken: gmailToken,
        to: parsedTo.valid,
        cc: parsedCc.valid,
        subject: cleanSubject,
        plainText,
        html,
      });

      setConfirmingSend(false);
      setSentResult({
        to: parsedTo.valid,
        cc: parsedCc.valid,
        subject: cleanSubject,
        messageId: sent.id,
      });
      onSentSuccess?.(parsedTo.valid.length + parsedCc.valid.length);
    } catch (err) {
      setConfirmingSend(false);
      if (err instanceof GmailAuthError) {
        clearGmailAccessToken();
        setGmailToken(null);
        setFormError(err.message);
      } else {
        setFormError(
          err instanceof Error
            ? err.message
            : 'Failed to send email via Gmail. Please try again.'
        );
      }
    } finally {
      setIsSending(false);
    }
  };

  const suggestionByItem = useMemo(() => {
    const map = new Map<number, DeviationAiSuggestion>();
    if (aiAnalysis) {
      for (const s of aiAnalysis.suggestions) {
        map.set(s.itemNumber, s);
      }
    }
    return map;
  }, [aiAnalysis]);

  const parsedToPreview = useMemo(
    () => parseAndValidateEmailList(toInput).valid,
    [toInput]
  );
  const parsedCcPreview = useMemo(
    () => parseAndValidateEmailList(ccInput).valid,
    [ccInput]
  );

  return (
    <div
      className="no-print fixed inset-0 z-50 bg-slate-950/60 backdrop-blur-[1px] flex items-center justify-center p-3 sm:p-5 overflow-y-auto"
      onClick={() => {
        if (!isSending) onClose();
      }}
      role="dialog"
      aria-modal="true"
      aria-labelledby="email-report-modal-title"
    >
      <div
        className="relative w-full max-w-5xl max-h-[92vh] bg-white border border-slate-200 rounded-xl shadow-2xl flex flex-col overflow-hidden"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Header */}
        <div className="px-5 py-4 border-b border-slate-200 flex items-center justify-between gap-4 bg-white shrink-0">
          <div className="min-w-0">
            <div className="flex items-center gap-2">
              <Mail className="w-4 h-4 text-red-700 shrink-0" />
              <h2
                id="email-report-modal-title"
                className="text-base font-bold text-slate-950 truncate"
              >
                Send Compliance Email Report
              </h2>
            </div>
            <p className="text-xs text-slate-500 mt-0.5 truncate font-mono tabular-nums">
              Report No.: {reportData.reportNo} · {reportData.storeLocation} ·{' '}
              {reportData.complianceRate !== null
                ? `${reportData.complianceRate}% Compliance`
                : 'Draft'}{' '}
              · {reportData.no}{' '}
              {reportData.no === 1 ? 'Deviation' : 'Deviations'}
            </p>
          </div>
          <button
            type="button"
            disabled={isSending}
            onClick={onClose}
            className="p-1.5 text-slate-400 hover:text-slate-800 hover:bg-slate-100 rounded-md transition-colors disabled:opacity-40"
            aria-label="Close email dialog"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Success Screen */}
        {sentResult ? (
          <div className="p-8 sm:p-10 text-center max-w-lg mx-auto space-y-4">
            <CheckCircle2 className="w-11 h-11 text-emerald-600 mx-auto" />
            <div>
              <h3 className="text-lg font-bold text-slate-950">
                Inspection Email Sent
              </h3>
              <p className="text-xs text-slate-600 mt-1.5 leading-relaxed">
                Your IQAF-005 compliance summary
                {includeAiSuggestions && aiAnalysis
                  ? ' with email-only AI deviation suggestions'
                  : ''}{' '}
                was delivered via Gmail.
              </p>
            </div>
            <div className="text-left bg-slate-50 border border-slate-200 rounded-lg p-4 text-xs space-y-1.5">
              <div>
                <span className="font-semibold text-slate-600">To:</span>{' '}
                <span className="text-slate-900">
                  {sentResult.to.join(', ')}
                </span>
              </div>
              {sentResult.cc.length > 0 && (
                <div>
                  <span className="font-semibold text-slate-600">Cc:</span>{' '}
                  <span className="text-slate-900">
                    {sentResult.cc.join(', ')}
                  </span>
                </div>
              )}
              <div>
                <span className="font-semibold text-slate-600">Subject:</span>{' '}
                <span className="text-slate-900">{sentResult.subject}</span>
              </div>
            </div>
            <div className="pt-2">
              <button
                type="button"
                onClick={onClose}
                className="px-5 h-9 text-xs font-semibold text-white bg-slate-900 hover:bg-slate-800 rounded-lg transition-colors"
              >
                Done
              </button>
            </div>
          </div>
        ) : (
          <>
            {/* Body: 2-column compose + preview */}
            <div className="flex-1 overflow-y-auto grid grid-cols-1 lg:grid-cols-12 divide-y lg:divide-y-0 lg:divide-x divide-slate-200">
              {/* Left Column: Recipients, Subject, Gmail Connection */}
              <div className="lg:col-span-5 p-5 space-y-4 bg-white">
                {/* Gmail Auth Panel */}
                <div className="border border-slate-200 rounded-lg p-3.5 bg-slate-50/70 space-y-2.5">
                  <div className="flex items-center justify-between gap-2">
                    <span className="text-xs font-semibold text-slate-800">
                      Gmail Sender Account
                    </span>
                    {gmailToken && (
                      <button
                        type="button"
                        disabled={isConnectingGmail}
                        onClick={() => handleConnectGmail(true)}
                        className="text-[11px] font-medium text-slate-600 hover:text-slate-900 underline"
                      >
                        Switch account
                      </button>
                    )}
                  </div>

                  {gmailToken ? (
                    <div className="flex items-center gap-2 text-xs text-emerald-800">
                      <ShieldCheck className="w-4 h-4 text-emerald-700 shrink-0" />
                      <span className="truncate font-medium">
                        Ready to send via {gmailEmail || 'your Gmail account'}
                      </span>
                    </div>
                  ) : (
                    <div className="space-y-2.5">
                      <p className="text-[11.5px] text-slate-600 leading-relaxed">
                        Sign in with Google to grant one-time send permission
                        for this session.
                      </p>
                      <button
                        type="button"
                        disabled={isConnectingGmail}
                        onClick={() => handleConnectGmail(false)}
                        className="w-full inline-flex items-center justify-center gap-2.5 h-10 px-4 text-xs font-semibold text-slate-800 bg-white border border-slate-300 hover:bg-slate-50 active:bg-slate-100 rounded-lg shadow-2xs transition-colors disabled:opacity-60"
                      >
                        {isConnectingGmail ? (
                          <Loader2 className="w-4 h-4 animate-spin text-slate-600" />
                        ) : (
                          <GoogleLogoSvg />
                        )}
                        <span>
                          {isConnectingGmail
                            ? 'Connecting Gmail…'
                            : 'Sign in with Google'}
                        </span>
                      </button>
                    </div>
                  )}
                </div>

                {/* Recipient Inputs */}
                <div className="space-y-3">
                  <label className="block">
                    <span className="block text-xs font-semibold text-slate-700 mb-1">
                      To <span className="text-red-700">*</span>
                    </span>
                    <input
                      type="text"
                      value={toInput}
                      onChange={(e) => {
                        setToInput(e.target.value);
                        setFormError(null);
                      }}
                      placeholder="areamanager@company.com, storemanager@company.com"
                      className="w-full h-9 px-3 text-xs bg-white border border-slate-300 rounded-md text-slate-900 placeholder:text-slate-400 focus:outline-none focus:ring-2 focus:ring-red-700/20 focus:border-red-700"
                    />
                    <span className="block text-[11px] text-slate-500 mt-1">
                      Separate multiple email addresses with commas
                    </span>
                  </label>

                  <label className="block">
                    <span className="block text-xs font-semibold text-slate-700 mb-1">
                      Cc (optional)
                    </span>
                    <input
                      type="text"
                      value={ccInput}
                      onChange={(e) => {
                        setCcInput(e.target.value);
                        setFormError(null);
                      }}
                      placeholder="qa.team@company.com"
                      className="w-full h-9 px-3 text-xs bg-white border border-slate-300 rounded-md text-slate-900 placeholder:text-slate-400 focus:outline-none focus:ring-2 focus:ring-red-700/20 focus:border-red-700"
                    />
                  </label>

                  <label className="block">
                    <span className="block text-xs font-semibold text-slate-700 mb-1">
                      Subject
                    </span>
                    <input
                      type="text"
                      maxLength={220}
                      value={subject}
                      onChange={(e) => {
                        setSubject(e.target.value);
                        setFormError(null);
                      }}
                      className="w-full h-9 px-3 text-xs bg-white border border-slate-300 rounded-md text-slate-900 focus:outline-none focus:ring-2 focus:ring-red-700/20 focus:border-red-700"
                    />
                  </label>

                  <label className="block">
                    <span className="block text-xs font-semibold text-slate-700 mb-1">
                      Introductory Note (optional)
                    </span>
                    <textarea
                      rows={3}
                      maxLength={1200}
                      value={senderNote}
                      onChange={(e) => setSenderNote(e.target.value)}
                      placeholder="Optional context or follow-up deadline for the branch team…"
                      className="w-full px-3 py-2 text-xs bg-white border border-slate-300 rounded-md text-slate-900 placeholder:text-slate-400 focus:outline-none focus:ring-2 focus:ring-red-700/20 focus:border-red-700 resize-y"
                    />
                  </label>
                </div>

                {/* Email-Only AI Suggestions Controls */}
                <div className="border-t border-slate-200 pt-3.5 space-y-2.5">
                  <label className="flex items-start gap-2.5 cursor-pointer select-none">
                    <input
                      type="checkbox"
                      checked={includeAiSuggestions}
                      onChange={(e) => setIncludeAiSuggestions(e.target.checked)}
                      className="mt-0.5 rounded border-slate-300 text-red-700 focus:ring-red-700"
                    />
                    <span className="text-xs text-slate-700 leading-snug">
                      <strong className="font-semibold text-slate-900">
                        Include AI suggestions for each deviation
                      </strong>
                      <span className="block text-[11px] text-slate-500 mt-0.5">
                        Email only — will not modify your saved checklist, PDF,
                        or Excel report.
                      </span>
                    </span>
                  </label>

                  {includeAiSuggestions && (
                    <button
                      type="button"
                      disabled={isGeneratingAi}
                      onClick={() => void handleGenerateAi()}
                      className="inline-flex items-center gap-1.5 px-3 h-8 text-xs font-semibold text-slate-800 bg-slate-100 hover:bg-slate-200 disabled:opacity-60 rounded-md transition-colors"
                    >
                      {isGeneratingAi ? (
                        <Loader2 className="w-3.5 h-3.5 animate-spin" />
                      ) : (
                        <RefreshCw className="w-3.5 h-3.5" />
                      )}
                      {isGeneratingAi
                        ? 'Generating AI Suggestions…'
                        : aiAnalysis
                          ? 'Regenerate AI Suggestions'
                          : 'Generate AI Suggestions'}
                    </button>
                  )}
                </div>

                {formError && (
                  <div className="p-3 rounded-lg bg-red-50 border border-red-200 text-xs text-red-800 flex items-start gap-2">
                    <AlertTriangle className="w-4 h-4 shrink-0 mt-0.5 text-red-700" />
                    <span>{formError}</span>
                  </div>
                )}
              </div>

              {/* Right Column: Email Content Preview & Editable Email-Only AI Suggestions */}
              <div className="lg:col-span-7 p-5 bg-slate-50 space-y-4">
                <div className="flex flex-wrap items-center justify-between gap-2">
                  <div>
                    <h3 className="text-xs font-bold text-slate-900 uppercase tracking-wide">
                      Email Report Preview
                    </h3>
                    <p className="text-[11px] text-slate-500">
                      Review compliance results and edit email-only AI
                      suggestions before sending
                    </p>
                  </div>
                  <span className="text-[11px] font-mono text-slate-600 tabular-nums">
                    {reportData.answered}/{TOTAL_ITEMS_COUNT} checked
                  </span>
                </div>

                {/* Compliance KPI Preview */}
                <div className="bg-white border border-slate-200 rounded-lg grid grid-cols-4 divide-x divide-slate-200 text-center">
                  <div className="p-3">
                    <div className="text-[10.5px] font-medium text-slate-500">
                      Score
                    </div>
                    <div className="text-lg font-bold font-mono tabular-nums text-slate-950 mt-0.5">
                      {reportData.complianceRate !== null
                        ? `${reportData.complianceRate}%`
                        : '—'}
                    </div>
                  </div>
                  <div className="p-3">
                    <div className="text-[10.5px] font-medium text-slate-500">
                      Yes
                    </div>
                    <div className="text-lg font-bold font-mono tabular-nums text-emerald-700 mt-0.5">
                      {reportData.yes}
                    </div>
                  </div>
                  <div className="p-3">
                    <div className="text-[10.5px] font-medium text-slate-500">
                      No
                    </div>
                    <div
                      className={`text-lg font-bold font-mono tabular-nums mt-0.5 ${
                        reportData.no > 0 ? 'text-red-700' : 'text-emerald-700'
                      }`}
                    >
                      {reportData.no}
                    </div>
                  </div>
                  <div className="p-3">
                    <div className="text-[10.5px] font-medium text-slate-500">
                      N/A
                    </div>
                    <div className="text-lg font-bold font-mono tabular-nums text-slate-700 mt-0.5">
                      {reportData.na}
                    </div>
                  </div>
                </div>

                {/* AI Generation Loading / Error / Summary */}
                {includeAiSuggestions && isGeneratingAi && (
                  <div className="bg-white border border-slate-200 rounded-lg p-4 flex items-center gap-3 text-xs text-slate-700">
                    <Loader2 className="w-4 h-4 animate-spin text-red-700 shrink-0" />
                    <div>
                      <div className="font-semibold text-slate-900">
                        Analyzing {reportData.deviations.length}{' '}
                        {reportData.deviations.length === 1
                          ? 'deviation'
                          : 'deviations'}{' '}
                        with AI…
                      </div>
                      <div className="text-[11px] text-slate-500 mt-0.5">
                        Drafting email-only corrective &amp; preventive
                        recommendations
                      </div>
                    </div>
                  </div>
                )}

                {includeAiSuggestions && aiError && !isGeneratingAi && (
                  <div className="bg-amber-50 border border-amber-200 rounded-lg p-3.5 text-xs text-amber-950 flex items-start justify-between gap-3">
                    <div className="flex items-start gap-2">
                      <AlertTriangle className="w-4 h-4 text-amber-700 shrink-0 mt-0.5" />
                      <div>
                        <div className="font-semibold">
                          AI suggestions unavailable
                        </div>
                        <div className="text-[11px] text-amber-900 mt-0.5">
                          {aiError}
                        </div>
                      </div>
                    </div>
                    <button
                      type="button"
                      onClick={() => void handleGenerateAi()}
                      className="px-2.5 h-7 text-[11px] font-semibold text-amber-950 bg-white border border-amber-300 hover:bg-amber-100 rounded-md shrink-0"
                    >
                      Retry
                    </button>
                  </div>
                )}

                {includeAiSuggestions &&
                  aiAnalysis?.overallEmailNote &&
                  !isGeneratingAi && (
                    <div className="bg-white border border-slate-200 border-l-4 border-l-red-700 rounded-lg p-3.5 space-y-1.5">
                      <div className="flex items-center gap-1.5 text-[11px] font-bold uppercase tracking-wide text-slate-600">
                        <Sparkles className="w-3.5 h-3.5 text-red-700" />
                        AI Executive Summary (Email Only)
                      </div>
                      <textarea
                        rows={2}
                        value={aiAnalysis.overallEmailNote}
                        onChange={(e) =>
                          setAiAnalysis((prev) =>
                            prev
                              ? { ...prev, overallEmailNote: e.target.value }
                              : prev
                          )
                        }
                        className="w-full text-xs text-slate-800 bg-slate-50 border border-slate-200 rounded p-2 focus:outline-none focus:border-slate-400 resize-y"
                      />
                    </div>
                  )}

                {/* Deviations & Per-Deviation AI Suggestions Preview */}
                <div className="space-y-2.5">
                  <div className="text-xs font-bold text-slate-900">
                    Deviations Included in Email ({reportData.deviations.length})
                  </div>

                  {reportData.deviations.length === 0 ? (
                    <div className="bg-emerald-50 border border-emerald-200 rounded-lg p-4 text-xs text-emerald-900 flex items-center gap-2.5">
                      <CheckCircle2 className="w-4 h-4 text-emerald-700 shrink-0" />
                      <span>
                        No deviations (&ldquo;No&rdquo;) recorded — the email
                        will report full compliance across checked items.
                      </span>
                    </div>
                  ) : (
                    <div className="space-y-3">
                      {reportData.deviations.map((dev) => {
                        const suggestion = suggestionByItem.get(dev.itemNumber);
                        return (
                          <div
                            key={dev.itemNumber}
                            className="bg-white border border-slate-200 rounded-lg overflow-hidden"
                          >
                            <div className="px-3.5 py-2 bg-red-50/70 border-b border-red-100 flex items-center justify-between gap-2 text-xs">
                              <span className="font-mono font-bold text-red-700 tabular-nums">
                                Item #{dev.itemNumber}
                              </span>
                              <span className="text-[11px] text-slate-600 truncate">
                                {dev.sectionCode}. {dev.sectionTitle}
                              </span>
                            </div>

                            <div className="p-3.5 space-y-2 text-xs">
                              <div className="font-semibold text-slate-900 leading-snug">
                                {dev.itemText}
                              </div>
                              <div className="grid grid-cols-1 sm:grid-cols-2 gap-2 text-[11.5px] text-slate-700 bg-slate-50 rounded p-2.5 border border-slate-100">
                                <div>
                                  <span className="font-semibold text-slate-500 block">
                                    Recorded Findings:
                                  </span>
                                  {dev.recordedDeviation || (
                                    <span className="italic text-slate-400">
                                      Not specified
                                    </span>
                                  )}
                                </div>
                                <div>
                                  <span className="font-semibold text-slate-500 block">
                                    Recorded Corrective Action:
                                  </span>
                                  {dev.recordedCorrectiveAction || (
                                    <span className="italic text-slate-400">
                                      Not specified
                                    </span>
                                  )}
                                </div>
                              </div>

                              {includeAiSuggestions && suggestion && (
                                <div className="border-l-2 border-slate-800 pl-3 py-1 space-y-2">
                                  <div className="flex items-center gap-1.5 text-[11px] font-bold text-slate-700">
                                    <Sparkles className="w-3 h-3 text-red-700" />
                                    AI Suggestion (Email Only — Editable)
                                  </div>

                                  <label className="block">
                                    <span className="text-[10.5px] font-semibold text-slate-500">
                                      Risk / Root Cause
                                    </span>
                                    <input
                                      type="text"
                                      value={suggestion.rootCauseHint}
                                      onChange={(e) =>
                                        updateSuggestionField(
                                          dev.itemNumber,
                                          'rootCauseHint',
                                          e.target.value
                                        )
                                      }
                                      className="mt-0.5 w-full px-2 py-1 text-[11.5px] text-slate-800 bg-slate-50 border border-slate-200 rounded focus:outline-none focus:border-slate-400"
                                    />
                                  </label>

                                  <label className="block">
                                    <span className="text-[10.5px] font-semibold text-slate-500">
                                      Suggested Corrective Action
                                    </span>
                                    <textarea
                                      rows={2}
                                      value={suggestion.recommendedAction}
                                      onChange={(e) =>
                                        updateSuggestionField(
                                          dev.itemNumber,
                                          'recommendedAction',
                                          e.target.value
                                        )
                                      }
                                      className="mt-0.5 w-full px-2 py-1 text-[11.5px] text-slate-900 bg-slate-50 border border-slate-200 rounded focus:outline-none focus:border-slate-400 resize-y"
                                    />
                                  </label>

                                  <label className="block">
                                    <span className="text-[10.5px] font-semibold text-slate-500">
                                      Preventive Control
                                    </span>
                                    <input
                                      type="text"
                                      value={suggestion.preventiveMeasure}
                                      onChange={(e) =>
                                        updateSuggestionField(
                                          dev.itemNumber,
                                          'preventiveMeasure',
                                          e.target.value
                                        )
                                      }
                                      className="mt-0.5 w-full px-2 py-1 text-[11.5px] text-slate-800 bg-slate-50 border border-slate-200 rounded focus:outline-none focus:border-slate-400"
                                    />
                                  </label>
                                </div>
                              )}
                            </div>
                          </div>
                        );
                      })}
                    </div>
                  )}
                </div>

                {/* Email Footer Preview Note */}
                <div className="pt-2 border-t border-slate-200 text-[11px] text-slate-500 space-y-0.5">
                  <div className="font-mono font-semibold text-slate-700">
                    Report No.: {reportData.reportNo}
                  </div>
                  <div>
                    Also included in email: Category A–Q compliance breakdown
                    table, Sign-Off status (Performed By, Acknowledged By, Noted
                    By: Area Manager), and basis notice ({IQAF_BASIS_STATEMENT}).
                  </div>
                </div>
              </div>
            </div>

            {/* Footer Action Bar */}
            <div className="px-5 py-3.5 border-t border-slate-200 bg-white flex flex-wrap items-center justify-between gap-3 shrink-0">
              <span className="text-[11px] text-slate-500">
                Requires explicit confirmation before sending via Gmail.
              </span>
              <div className="flex items-center gap-2">
                <button
                  type="button"
                  disabled={isSending}
                  onClick={onClose}
                  className="px-3.5 h-9 text-xs font-medium text-slate-700 bg-white border border-slate-200 hover:bg-slate-50 rounded-lg transition-colors"
                >
                  Cancel
                </button>
                <button
                  type="button"
                  disabled={isSending || (includeAiSuggestions && isGeneratingAi)}
                  onClick={handleRequestConfirmation}
                  className="inline-flex items-center gap-1.5 px-4 h-9 text-xs font-semibold text-white bg-red-700 hover:bg-red-800 disabled:opacity-50 rounded-lg transition-colors"
                >
                  <Send className="w-3.5 h-3.5" />
                  Review &amp; Send Email
                </button>
              </div>
            </div>
          </>
        )}

        {/* Mandatory Explicit Send Confirmation Overlay */}
        {confirmingSend && !sentResult && (
          <div className="absolute inset-0 z-10 bg-slate-950/55 flex items-center justify-center p-4">
            <div className="w-full max-w-md bg-white border border-slate-200 rounded-xl shadow-xl p-5 space-y-4">
              <div>
                <h3 className="text-base font-bold text-slate-950">
                  Confirm Email Delivery
                </h3>
                <p className="text-xs text-slate-600 mt-1">
                  Review the recipients and report details below before sending
                  this email from your Gmail account.
                </p>
              </div>

              <div className="bg-slate-50 border border-slate-200 rounded-lg p-3.5 text-xs space-y-2">
                <div>
                  <span className="font-semibold text-slate-500 block">
                    From (Gmail)
                  </span>
                  <span className="text-slate-900 font-medium">
                    {gmailEmail || 'Connected Google Account'}
                  </span>
                </div>
                <div>
                  <span className="font-semibold text-slate-500 block">To</span>
                  <span className="text-slate-900 break-words">
                    {parsedToPreview.join(', ')}
                  </span>
                </div>
                {parsedCcPreview.length > 0 && (
                  <div>
                    <span className="font-semibold text-slate-500 block">
                      Cc
                    </span>
                    <span className="text-slate-900 break-words">
                      {parsedCcPreview.join(', ')}
                    </span>
                  </div>
                )}
                <div>
                  <span className="font-semibold text-slate-500 block">
                    Subject
                  </span>
                  <span className="text-slate-900">
                    {stripHeaderBreaks(subject)}
                  </span>
                </div>
                <div className="pt-1.5 border-t border-slate-200 text-[11px] text-slate-600 tabular-nums">
                  Includes {reportData.complianceRate !== null ? `${reportData.complianceRate}%` : 'draft'} compliance summary, Category A–Q breakdown,{' '}
                  {reportData.deviations.length}{' '}
                  {reportData.deviations.length === 1
                    ? 'deviation'
                    : 'deviations'}
                  {includeAiSuggestions && aiAnalysis
                    ? ', and email-only AI suggestions.'
                    : '.'}
                </div>
              </div>

              <div className="flex items-center justify-end gap-2 pt-1">
                <button
                  type="button"
                  disabled={isSending}
                  onClick={() => setConfirmingSend(false)}
                  className="px-3.5 h-9 text-xs font-medium text-slate-700 bg-white border border-slate-200 hover:bg-slate-50 rounded-lg transition-colors"
                >
                  Back to Edit
                </button>
                <button
                  type="button"
                  disabled={isSending}
                  onClick={() => void handleConfirmSend()}
                  className="inline-flex items-center gap-1.5 px-4 h-9 text-xs font-semibold text-white bg-red-700 hover:bg-red-800 disabled:opacity-60 rounded-lg transition-colors"
                >
                  {isSending ? (
                    <Loader2 className="w-3.5 h-3.5 animate-spin" />
                  ) : (
                    <Send className="w-3.5 h-3.5" />
                  )}
                  {isSending ? 'Sending…' : 'Confirm & Send Email'}
                </button>
              </div>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
