import { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import {
  AlertTriangle,
  CheckCircle2,
  Loader2,
  Mail,
  RefreshCw,
  Send,
  ShieldCheck,
  Sparkles,
  X,
} from 'lucide-react';
import { IQAF_BASIS_STATEMENT, TOTAL_ITEMS_COUNT } from '../data/checklistData';
import {
  clearGmailAccessToken,
  connectGmailForSending,
  getGmailAccessToken,
  getGmailAccountEmail,
} from '../firebase';
import type { InspectionReport } from '../types/inspection';
import {
  type DeviationAiSuggestion,
  type EmailAiAnalysis,
  GmailAuthError,
  buildEmailHtml,
  buildEmailPlainText,
  computeReportEmailData,
  fetchAiDeviationSuggestions,
  parseAndValidateEmailList,
  sendInspectionEmailViaGmail,
  stripHeaderBreaks,
} from '../utils/emailReport';

interface EmailReportModalProps {
  report: InspectionReport;
  onClose: () => void;
  onSentSuccess?: (recipientCount: number) => void;
}

